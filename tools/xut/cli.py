import click

from xut import __version__

#: Marks status/PROGRESS.md, TODO.md and LOG.md as machine-generated (spec §11).
_GENERATED_COMMENT = "<!-- GENERATED by xut status generate — do not edit -->\n"


@click.group()
@click.version_option(__version__, prog_name="xut")
def main() -> None:
    """Xilinx primitive test-suite tooling."""


@main.command("fetch-docs")
@click.option("--local", type=click.Path(exists=True, dir_okay=False, path_type=Path))
def fetch_docs_cmd(local: Path | None) -> None:
    """Download UG953 into .cache/docs (or copy a local PDF there)."""
    from xut.docs_fetch import UG953, fetch, pdf_to_text
    from xut.paths import cache_dir

    pdf = fetch(UG953, cache_dir() / "docs", local=local)
    click.echo(f"pdf:  {pdf}\ntext: {pdf_to_text(pdf)}")


@main.group("catalog")
def catalog_grp() -> None:
    """Primitive catalog (catalog/<family>/<PRIM>.yaml)."""


EXPECTED_PRIMITIVES = 103


@catalog_grp.command("build")
def catalog_build_cmd() -> None:
    """Regenerate catalog/7series/*.yaml and catalog/EXTRACTION_REPORT.md."""
    from xut.catalog.build import FAMILY, build_all, render_report
    from xut.catalog.ug953 import names_from_text
    from xut.docs_fetch import UG953, fetch, pdf_to_text
    from xut.paths import VIVADO_RETARGET, VIVADO_UNISIM, cache_dir, repo_root, submodule_unisim

    text = pdf_to_text(fetch(UG953, cache_dir() / "docs"))
    names = names_from_text(text.read_text())
    if len(names) != EXPECTED_PRIMITIVES:
        raise click.ClickException(
            f"expected {EXPECTED_PRIMITIVES} UG953 primitive sections, found {len(names)}"
        )
    if VIVADO_UNISIM.is_dir():
        search = [VIVADO_UNISIM, VIVADO_RETARGET]
    else:
        search = [submodule_unisim()]
        click.echo(f"warning: {VIVADO_UNISIM} not found, using {search[0]}", err=True)
    root = repo_root()
    out = root / "catalog" / FAMILY
    report = build_all(text, names, out, search)
    sources = "the UNISIM models in " + ", ".join(f"`{s.name}/`" for s in search)
    (root / "catalog" / "EXTRACTION_REPORT.md").write_text(render_report(report, names, sources))
    only_in = sum(" only in " in line for line in report)
    click.echo(
        f"wrote {len(names)} entries to {out}; {len(report)} report lines ({only_in} only-in)"
    )


@main.group("status")
def status_grp() -> None:
    """Per-primitive status (status/<family>/<PRIM>.yaml, spec §11)."""


@status_grp.command("init")
def status_init_cmd() -> None:
    """Write a status stub for every catalog entry that has none yet.

    Never overwrites an existing status/<family>/<PRIM>.yaml.
    """
    from xut.catalog.build import FAMILY
    from xut.catalog.model import load_entry
    from xut.paths import repo_root
    from xut.status import dump_stub
    from xut.workunits import load_units

    root = repo_root()
    unit_of = {p: name for name, u in load_units(root).items() for p in u.primitives}
    cat_dir = root / "catalog" / FAMILY
    out_dir = root / "status" / FAMILY
    out_dir.mkdir(parents=True, exist_ok=True)
    names = sorted(f.stem for f in cat_dir.glob("*.yaml") if not f.name.endswith(".overrides.yaml"))
    written = 0
    for name in names:
        dest = out_dir / f"{name}.yaml"
        if dest.exists():
            continue
        entry = load_entry(FAMILY, name, root)
        dest.write_text(dump_stub(entry, unit_of[name]))
        written += 1
    click.echo(f"wrote {written} new stub(s); {len(names)} catalog entries, {out_dir}")


def _generated_header(root: Path, branch: str) -> str:
    """The header every generated status file starts with: the do-not-edit marker
    plus the generation time and git HEAD (spec §11; not part of any `render_*`
    function's output, so that output stays deterministic apart from this header)."""
    proc = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], cwd=root, capture_output=True, text=True
    )
    head = proc.stdout.strip() if proc.returncode == 0 else "unknown"
    now = datetime.now(UTC).strftime("%Y-%m-%dT%H:%MZ")
    return _GENERATED_COMMENT + f"\n_Generated {now} at HEAD `{head}` on branch `{branch}`._\n\n"


@status_grp.command("generate")
@click.option("--force", is_flag=True, help="Write even when not on main.")
def status_generate_cmd(force: bool) -> None:
    """Regenerate status/PROGRESS.md, TODO.md and LOG.md (spec §11).

    Refuses unless the current branch is `main`, since branches never commit these
    generated files (spec §11, global constraints Review Focus item 5).
    """
    from xut.catalog.build import FAMILY
    from xut.paths import repo_root
    from xut.status import current_branch, load_status, render_log, render_progress, render_todo
    from xut.workunits import load_units

    try:
        branch = current_branch()
    except RuntimeError as e:
        # current_branch() raises a plain RuntimeError (it doesn't depend on
        # click); turn it into the same clean, no-traceback error every other
        # user-facing failure in this command gets.
        raise click.ClickException(str(e)) from e
    if branch != "main" and not force:
        raise click.ClickException(
            f"refusing to write generated status files on branch {branch!r}: "
            "only main regenerates them (pass --force to override)"
        )

    root = repo_root()
    units = load_units(root)
    status_dir = root / "status" / FAMILY
    statuses = [load_status(p) for p in sorted(status_dir.glob("*.yaml"))]

    header = _generated_header(root, branch)
    out_dir = root / "status"
    (out_dir / "PROGRESS.md").write_text(header + render_progress(statuses, units))
    (out_dir / "TODO.md").write_text(header + render_todo(statuses, units))
    (out_dir / "LOG.md").write_text(header + render_log(root / "log"))
    click.echo(f"wrote PROGRESS.md, TODO.md, LOG.md to {out_dir} ({len(statuses)} statuses)")


@main.command("lint")
@click.option(
    "--branch",
    "branch_mode",
    is_flag=True,
    help="Also check branch-ownership and generated-file rules against origin/main...HEAD.",
)
def lint_cmd(branch_mode: bool) -> None:
    """Enforce branch ownership, SPDX headers, generated files, docs and status schema.

    Exits non-zero iff any error-severity issue was found; warnings are printed but never
    fail the build.
    """
    from xut.lint import lint
    from xut.paths import repo_root

    root = repo_root()
    issues, warnings = lint(root, branch_mode)
    for w in warnings:
        click.echo(f"warning: {w}", err=True)
    for issue in sorted(issues, key=lambda i: (i.path, i.rule)):
        click.echo(f"{issue.severity} {issue.rule} {issue.path}: {issue.message}")
    errors = sum(1 for i in issues if i.severity == "error")
    click.echo(f"{len(issues)} issue(s): {errors} error(s), {len(issues) - errors} warning(s)")
    if errors:
        raise SystemExit(1)
