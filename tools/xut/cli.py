@status_grp.command("init")
@click.option(
    "--refresh-bins",
    is_flag=True,
    help="also rewrite the coverage bins of never-recorded stubs (tree_hash null) to the "
    "current catalog bins; recorded status files are never touched",
)
def status_init_cmd(refresh_bins: bool) -> None:
    """Write a status stub for every catalog entry that has none yet.

    Never overwrites an existing status/<family>/<PRIM>.yaml, except that
    --refresh-bins updates the bins of a stub no `xut status record` has touched.
    """
    from xut.catalog.model import load_entry
    from xut.paths import repo_root
    from xut.status import dump_stub
    from xut.status import refresh_bins as refresh
    from xut.workunits import load_family, load_units

    root = repo_root()
    family = load_family(root)
    unit_of = {p: name for name, u in load_units(root).items() for p in u.primitives}
    cat_dir = root / "catalog" / family
    out_dir = root / "status" / family
    out_dir.mkdir(parents=True, exist_ok=True)
    names = sorted(f.stem for f in cat_dir.glob("*.yaml") if not f.name.endswith(".overrides.yaml"))
    orphans = [n for n in names if n not in unit_of]
    if orphans:
        raise ConfigError(
            f"catalog primitive(s) in no work unit of docs/work-units.yaml: {', '.join(orphans)}"
        )
    written = refreshed = 0
    for name in names:
        dest = out_dir / f"{name}.yaml"
        if dest.exists():
            if refresh_bins:
                try:
                    refreshed += refresh(dest, load_entry(family, name, root))
                except (yaml.YAMLError, jsonschema.ValidationError) as e:
                    raise _schema_error(dest, root, e) from e
            continue
        entry = load_entry(family, name, root)
        dest.write_text(dump_stub(entry, unit_of[name]))
        written += 1
    msg = f"wrote {written} new stub(s); {len(names)} catalog entries, {out_dir}"
    if refresh_bins:
        msg += f"; refreshed the bins of {refreshed} never-recorded stub(s)"
    click.echo(msg)


@status_grp.command("record")
@click.argument("prims", nargs=-1)
@click.option("--unit", "unit_name", help="record every primitive of this work unit")
@click.option(
    "--model-source",
    default=REFERENCE_MODEL_SOURCE,
    show_default=True,
    help="whose results to record: unisim-2025.2 fills `results`; any other source "
    "fills `results_by_model_source.<source>`",
)
def status_record_cmd(prims: tuple[str, ...], unit_name: str | None, model_source: str) -> None:
    """Record PRIM...'s (or --unit's) results from build/ into status/<family>/<PRIM>.yaml.

    Results come from `xut run`'s result.json files for --model-source. Refuses when the
    primitive's tests, shared unit code, golden model or overrides have uncommitted
    changes (the tree hash would not describe them). Warnings (e.g. an exercised bin the
    golden model did not reach) go to stderr.
    """
    from xut.paths import repo_root
    from xut.status import record
    from xut.testspec import discover
    from xut.workunits import load_family, load_units

    if bool(prims) == bool(unit_name):
        raise click.UsageError("give either PRIM... or --unit NAME")
    root = repo_root()
    family = load_family(root)
    if unit_name:
        units = load_units(root)
        if unit_name not in units:
            raise ConfigError(f"unknown work unit {unit_name!r} (see docs/work-units.yaml)")
        tested = {c.prim for c in discover(root) if c.family == family}
        prims = tuple(p for p in units[unit_name].primitives if p in tested)
        for p in units[unit_name].primitives:
            if p not in tested:
                click.echo(f"skipped {p}: no tests yet")
        if not prims:
            raise ConfigError(f"work unit {unit_name!r} has no tests to record yet")

    def warn(message: str) -> None:
        click.echo(f"warning: {message}", err=True)

    for prim in prims:
        s = record(root, prim, family=family, model_source=model_source, warn=warn)
        results = (
            s["results"]
            if model_source == REFERENCE_MODEL_SOURCE
            else s["results_by_model_source"][model_source]
        )
        counts = Counter(results.values())
        line = f"wrote status/{family}/{prim}.yaml ({model_source}): " + ", ".join(
            f"{n} {v}" for v, n in sorted(counts.items())
        )
        if model_source == REFERENCE_MODEL_SOURCE:  # coverage is the reference's only
            cov = s["coverage"]
            line += (
                f"; coverage {len(cov['covered'])}/{len(cov['covered']) + len(cov['uncovered'])}"
            )
        click.echo(line)


def _generated_header(root: Path, branch: str) -> str:
    """The header every generated status file starts with: the do-not-edit marker
    plus the generation time and git HEAD (spec §11; not part of any `render_*`
    function's output, so that output stays deterministic apart from this header)."""
    from xut import provenance

    head, now = provenance.short_head(root), provenance.utc_stamp()
    return _GENERATED_COMMENT + f"\n_Generated {now} at HEAD `{head}` on branch `{branch}`._\n\n"


@status_grp.command("generate")
@click.option("--force", is_flag=True, help="Write even when not on main.")
def status_generate_cmd(force: bool) -> None:
    """Regenerate status/PROGRESS.md, TODO.md and LOG.md (spec §11), and PORTABILITY.md
    when build/portability/*.json holds a full smoke run (`xut portability`).

    Refuses unless the current branch is `main`, since branches never commit these
    generated files (spec §11, global constraints Review Focus item 5).
    """
    from xut.paths import repo_root
    from xut.status import (
        current_branch,
        load_status,
        render_log,
        render_portability,
        render_progress,
        render_todo,
    )
    from xut.workunits import load_family, load_units

    branch = current_branch()
    if branch != "main" and not force:
        raise click.ClickException(
            f"refusing to write generated status files on branch {branch!r}: "
            "only main regenerates them (pass --force to override)"
        )

    root = repo_root()
    units = load_units(root)
    status_dir = root / "status" / load_family(root)
    statuses = []
    for p in sorted(status_dir.glob("*.yaml")):
        try:
            statuses.append(load_status(p))
        except (yaml.YAMLError, jsonschema.ValidationError) as e:
            raise _schema_error(p, root, e) from e

    header = _generated_header(root, branch)
    out_dir = root / "status"
    (out_dir / "PROGRESS.md").write_text(header + render_progress(statuses, units))
    (out_dir / "TODO.md").write_text(header + render_todo(statuses, units))
    (out_dir / "LOG.md").write_text(header + render_log(root / "log"))
    written = ["PROGRESS.md", "TODO.md", "LOG.md"]
    portability = render_portability(root)
    if portability is not None:  # only when a smoke run left build/portability/*.json
        (out_dir / "PORTABILITY.md").write_text(portability)
        written.append("PORTABILITY.md")
    click.echo(f"wrote {', '.join(written)} to {out_dir} ({len(statuses)} statuses)")


@main.command("lint")
@click.option(
    "--branch",
    "branch_mode",
    is_flag=True,
    help="Also check branch-ownership and generated-file rules against <base>...HEAD.",
)
@click.option(
    "--base",
    default="origin/main",
    show_default=True,
    help="Base ref to diff against in --branch mode (e.g. origin/<PR base branch> in CI).",
)
def lint_cmd(branch_mode: bool, base: str) -> None:
    """Enforce branch ownership, SPDX headers, generated files, docs and status schema.

    Exits non-zero iff any error-severity issue was found; warnings are printed but never
    fail the build.
    """
    from xut.lint import lint
    from xut.paths import repo_root

    root = repo_root()
    issues, warnings = lint(root, branch_mode, base=base)
    for w in warnings:
        click.echo(f"warning: {w}", err=True)
    for issue in sorted(issues, key=lambda i: (i.path, i.rule)):
        click.echo(f"{issue.severity} {issue.rule} {issue.path}: {issue.message}")
    errors = sum(1 for i in issues if i.severity == "error")
    click.echo(f"{len(issues)} issue(s): {errors} error(s), {len(issues) - errors} warning(s)")
    if errors:
        raise SystemExit(1)


