#: Marks status/PROGRESS.md, TODO.md and LOG.md as machine-generated (spec §11).
_GENERATED_COMMENT = "<!-- GENERATED by xut status generate — do not edit -->\n"


class _CleanErrorGroup(click.Group):
    """Root command group: any `XutError` raised by a subcommand becomes a clean
    `Error: <message>` and exit 1 (via `click.ClickException`), never a traceback.
    Nested groups propagate to this one, so every command shares the one handler."""

    def invoke(self, ctx: click.Context) -> object:
        try:
            return super().invoke(ctx)
        except XutError as e:
            raise click.ClickException(str(e)) from e


def _schema_error(path: Path, root: Path, e: Exception) -> ConfigError:
    """A `ConfigError` naming the offending file and the first schema/YAML problem."""
    rel = path.relative_to(root) if path.is_relative_to(root) else path
    if isinstance(e, jsonschema.ValidationError):
        return ConfigError(f"{rel}: {e.json_path}: {e.message}")
    return ConfigError(f"{rel}: invalid YAML: {str(e).splitlines()[0]}")


