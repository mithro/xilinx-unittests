@vec_grp.command("check")
@click.argument("path", type=click.Path(exists=True, dir_okay=False, path_type=Path))
@click.option(
    "--map",
    "map_path",
    type=click.Path(exists=True, dir_okay=False, path_type=Path),
    required=True,
    help="the wrapper's xut_dut.map.json",
)
def vec_check_cmd(path: Path, map_path: Path) -> None:
    """Validate an .xvec against a wrapper map (spec §5.1 class rules).

    Prints every error and whether the file is hardware-renderable; exits 1 on errors.
    """
    from xut.formats.xvec import XvecError, load
    from xut.validate import validate
    from xut.wrap import DutMap

    try:
        vec = load(path)
    except XvecError as e:
        raise XvecError(f"{path}: {e}") from e
    r = validate(vec, DutMap.load(map_path))
    for e in r.errors:
        click.echo(f"error: {e}")
    if r.errors:  # an invalid file has no renderability (review A4)
        click.echo("hw_renderable: n/a (invalid)")
        raise SystemExit(1)
    click.echo(f"hw_renderable: {'yes' if r.hw_renderable else 'no'}")
    for h in r.hw_reasons:
        click.echo(f"  reason: {h}")
    # 2-state runners (Verilator, hw) must skip a stimulus that drives x/z.
    click.echo(f"x_inputs: {'yes' if r.x_inputs else 'no'}")


def _select_cases(root: Path, cases: list, selectors: tuple[str, ...]) -> list:
    """The cases ``selectors`` match (all of them when there are none), for ``xut run``
    and ``xut crosscheck``. A selector matching no test is an error (a typo must not pass
    in CI), except ``unit:<name>`` for a work unit of docs/work-units.yaml that has no
    tests yet: that selects nothing, like a --level/--style filter leaving nothing."""
    from xut.testspec import select
    from xut.workunits import load_units

    if not selectors:
        return cases
    unmatched = [sel for sel in selectors if not select(cases, [sel])]
    if any(sel.startswith("unit:") for sel in unmatched):
        try:
            units = load_units(root)
        except FileNotFoundError:
            units = {}
        unmatched = [
            sel
            for sel in unmatched
            if not (sel.startswith("unit:") and sel.removeprefix("unit:") in units)
        ]
    if unmatched:
        raise XutError(f"no tests matched selector(s) {unmatched}")
    return select(cases, list(selectors))


@main.command("run")
@click.argument("selectors", nargs=-1)
@click.option(
    "--runner",
    "runner_names",
    multiple=True,
    help="repeatable; default: every runner (iverilog-vz follows verilator)",
)
@click.option("--flow", type=click.Choice(["rtl"]), default="rtl", show_default=True)
@click.option("--model-source", default="auto", show_default=True)
@click.option("--style", "styles", multiple=True, type=click.Choice(["vector", "sv", "cocotb"]))
@click.option("--level", "levels", multiple=True, type=click.Choice(["L0", "L1", "L2", "L3"]))
@click.option(
    "--seed",
    type=int,
    help="stimulus/cocotb/sv seed (default: crc32 of the test id, the SAME on every run: "
    "pass --seed to explore others; every cocotb fail/error reason names its seed)",
)
@click.option(
    "--jobs", type=click.IntRange(min=1), default=1, show_default=True, callback=_jobs_cap
)
@click.option("--timeout", type=click.IntRange(min=1), help="per-runner seconds (default 600)")
def run_cmd(
    selectors: tuple[str, ...],
    runner_names: tuple[str, ...],
    flow: str,
    model_source: str,
    styles: tuple[str, ...],
    levels: tuple[str, ...],
    seed: int | None,
    jobs: int,
    timeout: int | None,
) -> None:
    """Run tests: SELECT is a test-id glob, a primitive name or unit:<name> (default: all).

    Every selected (test, runner) pair writes
    build/<flow>/<runner>/<model-source>/<test-id>/result.json, and the run writes
    build/<flow>/summary-<model-source>.json. Exits 1 if any result is fail or error,
    or if a SELECT matches no test at all (filters leaving nothing selected exit 0, and
    so does unit:<name> for a work unit with no tests yet).
    Skip reasons are printed, one line per distinct reason.
    """
    from xut import modelsrc
    from xut import run as run_mod
    from xut.paths import repo_root
    from xut.runners import RUNNERS
    from xut.runners.base import RunContext
    from xut.testspec import discover

    unknown = sorted(set(runner_names) - set(RUNNERS))
    if unknown:
        raise XutError(f"unknown runner(s) {unknown} (known: {sorted(RUNNERS)})")
    # iverilog-vz is not in the default list: it comes with verilator (spec §6.2)
    names = list(dict.fromkeys(runner_names)) or [r for r in RUNNERS if r != "iverilog-vz"]
    names = run_mod.with_companions(names)

    root = repo_root()
    # A selector matching no test at all is an error (a typo must not pass in CI);
    # --level/--style filtering the matches down to nothing is not (exit 0 below).
    cases = _select_cases(root, discover(root), selectors)
    cases = [
        c for c in cases if (not levels or c.level in levels) and (not styles or c.style in styles)
    ]
    if not cases:
        what = [*selectors, *(f"--level {v}" for v in levels), *(f"--style {s}" for s in styles)]
        click.echo(f"no tests selected ({' '.join(what) or 'no tests under tests/'})")
        return

    ctx = RunContext(root, flow, modelsrc.resolve(model_source), seed, {}, timeout, jobs)
    try:
        results = run_mod.run_tests(cases, names, ctx)
    except KeyboardInterrupt:
        click.echo(
            "interrupted: queued runs cancelled; partial summary in "
            f"build/{flow}/summary-{ctx.model_source.name}.json",
            err=True,
        )
        raise SystemExit(130) from None

    ran = list(dict.fromkeys(r.runner for r in results))
    status = {(r.test_id, r.runner): r.status for r in results}
    id_w = max(len("test"), *(len(c.id) for c in cases))
    click.echo("")
    click.echo(f"{'test':<{id_w}}  " + "  ".join(f"{n:<{max(8, len(n))}}" for n in ran))
    for c in cases:
        cells = [f"{status.get((c.id, n), '-'):<{max(8, len(n))}}" for n in ran]
        click.echo(f"{c.id:<{id_w}}  " + "  ".join(cells))
    bad = [r for r in results if r.status in ("fail", "error")]
    for r in bad:
        click.echo(f"{r.status}: {r.test_id} {r.runner}: {r.reason}")
    skips = Counter(r.reason for r in results if r.status == "skip")
    for why, n in skips.items():
        click.echo(f"skip: {why} ({n} result{'s' if n > 1 else ''})")
    if bad:
        raise SystemExit(1)


@main.command("crosscheck")
@click.argument("selectors", nargs=-1)
@click.option(
    "--write-findings",
    is_flag=True,
    help="write a findings/<PRIM>-<slug>.md stub for every unlisted finding (never "
    "overwrites; a known-divergence already has its finding)",
)
@click.option(
    "--model-source",
    help="restrict the report to this model source's results (default: every source)",
)
@click.option("--style", "styles", multiple=True, type=click.Choice(["vector", "sv", "cocotb"]))
@click.option("--level", "levels", multiple=True, type=click.Choice(["L0", "L1", "L2", "L3"]))
@click.option(
    "--strict",
    is_flag=True,
    help="every selected test must have been cross-checked: a not-run or uncompared "
    "test exits 4, including one a runner could not run (CI: select exactly what was "
    "run, e.g. with --level/--style)",
)
def crosscheck_cmd(
    selectors: tuple[str, ...],
    write_findings: bool,
    model_source: str | None,
    styles: tuple[str, ...],
    levels: tuple[str, ...],
    strict: bool,
) -> None:
    """Cross-check every runner's traces of each selected test (spec §8).

    SELECT is a test-id glob, a primitive name or unit:<name> (default: all). Traces are
    compared like-for-like, per model source. Prints the matrix, findings and issues,
    and writes build/crosscheck/<test-id>.json.

    \b
    Exit status (ruling S23):
      0  clean: every compared result agrees, or disagrees only as listed
      3  a finding not listed in the test's expected_divergence (wins over 4)
      4  incomplete: an error, a fail no disagreement explains, results measured at
         mixed or dirty trees, traces sharing no configuration, or no two traces
         to compare
      1  a user error (e.g. a selector matching no test); 2  a usage error
    With --strict, any selected test that is not-run or uncompared is also 4, so a
    partial or crashed `xut run` can never look clean.
    """
    from xut import crosscheck as xc
    from xut.paths import repo_root
    from xut.testspec import discover

    root = repo_root()
    if model_source is not None:
        from xut.modelsrc import known_model_sources

        known = {*known_model_sources(), *(p.name for p in root.glob("build/*/*/*") if p.is_dir())}
        if model_source not in known:
            raise XutError(
                f"unknown model source {model_source!r} (known: {', '.join(sorted(known))})"
            )
    cases = _select_cases(root, discover(root), selectors)
    cases = [
        c for c in cases if (not levels or c.level in levels) and (not styles or c.style in styles)
    ]
    if not cases:
        # As `xut run`: a selection with no tests (e.g. a work unit before its tests
        # exist) checks nothing and is not an error, strict or not; a SELECT that
        # matches no test at all was already an error above (`_select_cases`).
        click.echo(f"no tests selected ({' '.join(selectors) or 'no tests under tests/'})")
        return
    reports = []
    for case in cases:
        rep = xc.check(root, case, model_source=model_source)
        reports.append(rep)
        xc.write_report(root, rep)
        click.echo(xc.render(rep))
        if write_findings and not rep.provenance_ok:
            click.echo(
                f"{case.id}: not writing findings: its results are not all from one clean tree"
            )
        elif write_findings:
            for f in rep.unlisted:
                action, p = xc.record_finding(root, case.prim, f)
                if p is not None:
                    click.echo(f"{action}{'' if action == 'wrote' else ':'} {p.relative_to(root)}")
    verdicts = Counter(r.verdict for r in reports)
    click.echo("crosscheck: " + ", ".join(f"{n} {v}" for v, n in sorted(verdicts.items())))
    codes = {r.exit_code for r in reports}
    code = next((c for c in (xc.EXIT_FINDING, xc.EXIT_INCOMPLETE) if c in codes), 0)
    unchecked = [r for r in reports if r.verdict in ("not-run", "uncompared")]
    if code == 0 and (strict and unchecked or len(unchecked) == len(reports)):
        code = xc.EXIT_INCOMPLETE  # no cross-checked evidence (for strict: anywhere) is never clean
        if strict:
            for r in unchecked:
                click.echo(f"strict: {r.case.id} was {r.verdict}")
    if code:
        raise SystemExit(code)


@main.command("portability")
@click.option(
    "--model-source",
    "model_sources",
    multiple=True,
    help="repeatable (default: auto)",
)
@click.option(
    "--jobs", type=click.IntRange(min=1), default=1, show_default=True, callback=_jobs_cap
)
@click.option("--models", "models_glob", help="only the models matching this glob (a partial run)")
@click.option("--write", is_flag=True, help="write status/PORTABILITY.md (main only)")
@click.option("--force", is_flag=True, help="--write even when not on main")
@click.option(
    "--no-check",
    is_flag=True,
    help="use the manifest's equivalence verdicts as they are (no xut verilatorize --check)",
)
def portability_cmd(
    model_sources: tuple[str, ...],
    jobs: int,
    models_glob: str | None,
    write: bool,
    force: bool,
    no_check: bool,
) -> None:
    """Smoke-run every UNISIM model on Icarus and Verilator (spec §6.2 portability table).

    Writes build/portability/<model-source>.json per model source, and renders every full
    run there into build/portability/PORTABILITY.md, or with --write into
    status/PORTABILITY.md (refused unless on main or --force; never with --models). Prints
    `progress: done=N total=M elapsed_s=E` every 10 s while the smoke scripts run.
    """
    from xut import modelsrc, portability, provenance
    from xut.paths import repo_root
    from xut.status import current_branch

    if write and models_glob:
        raise XutError("--write needs a full run: --models makes a partial one")
    if write and not force and (branch := current_branch()) != "main":
        raise click.ClickException(
            f"refusing to write status/PORTABILITY.md on branch {branch!r}: only main "
            "regenerates it (pass --force to override)"
        )
    root = repo_root()
    runs = {}
    for name in model_sources or ("auto",):
        ms = modelsrc.resolve(name)
        rows = portability.run_smoke(
            ms, jobs=jobs, models=models_glob, root=root, check=not no_check, progress=click.echo
        )
        runs[ms.name] = rows
        for tool in portability.TOOLS:
            yes = sum(r.ok(tool) for r in rows)
            click.echo(f"{ms.name}: {tool}: {yes} yes, {len(rows) - yes} no")
    if models_glob:  # partial: render only what ran, next to its partial results
        rows_by_source, meta = (
            runs,
            {
                "generated": provenance.utc_stamp(),
                "head": provenance.short_head(root),
                "image": "-",
                "digest": "-",
            },
        )
        dest = root / "build" / "portability" / "partial" / "PORTABILITY.md"
    else:
        rows_by_source, meta = portability.load_results(root)
        dest = root / ("status" if write else "build/portability") / "PORTABILITY.md"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(portability.render(rows_by_source, meta))
    click.echo(f"wrote {dest}")


@main.command("verilatorize")
@click.argument("models", nargs=-1)
@click.option("--model-source", default="auto", show_default=True)
@click.option(
    "--jobs", type=click.IntRange(min=1), default=1, show_default=True, callback=_jobs_cap
)
@click.option(
    "--check",
    is_flag=True,
    help="Equivalence-check every transformed model against its original (spec §6.2).",
)
def verilatorize_cmd(models: tuple[str, ...], model_source: str, jobs: int, check: bool) -> None:
    """Rewrite procedural assign/deassign in UNISIM models for Verilator (spec §6.2).

    Writes build/verilatorized/<model-source>/<MODEL>.v and manifest.json (never
    committed). Incremental: a model is redone only when its source changed. MODEL
    restricts the run (default: every model of the source). --check then runs the
    mandatory equivalence stimulus on the original and the transformed model of every
    transformed model, under its default and every generate configuration, and of every
    model over a transformed dependency (its original hierarchy against the vz hierarchy,
    ruling S45); it exits 1 when any check is not a pass.
    """
    from xut import modelsrc
    from xut.verilatorize.driver import STATUSES, verilatorize, vz_dir

    ms = modelsrc.resolve(model_source)
    man = verilatorize(ms, list(models) or None, jobs=jobs, progress=click.echo, check=check)
    shown = {m: e for m, e in man.models.items() if not models or m in models}
    counts = Counter(e.status for e in shown.values())
    click.echo(
        f"{ms.name}: "
        + ", ".join(f"{counts.get(s, 0)} {s}" for s in STATUSES)
        + f" (output: {vz_dir(ms)})"
    )
    for m, e in sorted(shown.items()):
        if e.status == "transformed":
            click.echo(
                f"transformed: {m}: triggers={','.join(e.triggers)} "
                f"enablers={','.join(e.enablers) or '-'} configs={len(e.generate_configs)}"
            )
    for m, e in sorted(shown.items()):
        if e.status == "unsupported":
            why = e.reason.splitlines()[0]
            click.echo(f"unsupported: {m}: {why.removeprefix(f'{m}: ')}")
    for m, e in sorted(shown.items()):
        if e.status != "unsupported" and e.depends_on_unsupported:
            click.echo(f"blocked: {m}: its hierarchy holds {','.join(e.depends_on_unsupported)}")
        elif e.status == "unchanged" and e.depends_on_transformed:
            click.echo(f"gated: {m}: over {','.join(e.depends_on_transformed)}")
    if not check:
        return
    results: Counter[str] = Counter()
    for m, e in sorted(shown.items()):
        if not e.gated:
            continue
        for key, status in sorted(e.equiv.items()):
            results[status] += 1
            oracle = e.equiv_oracle.get(key) or "-"
            click.echo(f"equiv: {status}: {m} [{key}] oracle={oracle}")
    click.echo(
        "equiv: "
        + ", ".join(f"{results.get(s, 0)} {s}" for s in ("pass", "fail", "error"))
        + f" (details: {vz_dir(ms) / 'equiv'})"
    )
    if results.get("fail") or results.get("error"):
        raise SystemExit(1)
