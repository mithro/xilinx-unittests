def _errors(log):
    """Icarus error messages without their file:line prefix (lines shift in the rewrite)."""
    return {
        re.sub(r"^\S+?:\d+: ", "", line)
        for line in log.read_text().splitlines()
        if "error" in line and not line.startswith("$ ")
    }


def _with_defaults(path, model, cfg):
    """``path``'s text with the defaults of ``model``'s parameters in ``cfg`` replaced."""
    from xut.verilatorize.analyze import _param_decls, _Source

    src = _Source(path)
    tree = pyslang.syntax.SyntaxTree.fromFile(str(path))
    edits = []
    for name, _, init, _ in _param_decls(tree, model):
        if name in cfg:
            r = init.sourceRange
            edits.append((src.char(r.start.offset), src.char(r.end.offset), cfg[name]))
    assert {n for n in cfg} <= {n for n, *_ in _param_decls(tree, model)}, cfg
    text = src.text
    for a, b, rep in sorted(edits, reverse=True):
        text = text[:a] + rep + text[b:]
    return text


def _lint(ms, model, work, configs):
    """(verilator ok under the default and every generate configuration, icarus ok, icarus
    errors the ORIGINAL model has too) for ``model``'s transformed copy, logging to ``work``."""
    from xut.container import executor_for
    from xut.verilatorize.driver import model_files, vz_dir

    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    ex = executor_for(ms, work)
    libs = [a for d in ms.search for a in ("-y", ex.guest(d))]
    src, glbl = ex.guest(vz_dir(ms) / f"{model}.v"), ex.guest(ms.glbl)
    vl = ex.run(
        ["verilator", "--lint-only", "--timing", "-Wno-fatal", "-Wno-lint", "-Wno-style",
         "-Wno-MULTITOP", "-y", ex.guest(vz_dir(ms)), *libs, "+libext+.v", src, glbl],
        cwd=work, log=work / "verilator.log", timeout_s=600,
    )  # fmt: skip
    for k, cfg in enumerate((c for c in configs if c), start=1):
        # -G does not reach a model beside glbl (two tops), and a wrapper instance trips
        # Verilator's "tristate in top-level IO" on the FD* models: lint a copy of the
        # transformed model with the parameter defaults set to the configuration instead.
        copy = work / f"cfg{k}" / f"{model}.v"
        copy.parent.mkdir()
        write_text(copy, _with_defaults(vz_dir(ms) / f"{model}.v", model, cfg))
        vl |= ex.run(
            ["verilator", "--lint-only", "--timing", "-Wno-fatal", "-Wno-lint", "-Wno-style",
             "-Wno-MULTITOP", "-y", ex.guest(vz_dir(ms)), *libs, "+libext+.v",
             ex.guest(copy), glbl],
            cwd=work, log=work / f"verilator-cfg{k}.log", timeout_s=600,
        )  # fmt: skip
    iv = ex.run(
        ["iverilog", "-g2012", "-o", "sim.vvp", "-s", model, "-s", "glbl",
         "-y", ex.guest(vz_dir(ms)), *libs, src, glbl],
        cwd=work, log=work / "iverilog.log", timeout_s=600,
    )  # fmt: skip
    if iv == 0:
        return vl == 0, True, False
    orig = ex.guest(model_files(ms)[model])
    ex.run(
        ["iverilog", "-g2012", "-o", "orig.vvp", "-s", model, "-s", "glbl", *libs, orig, glbl],
        cwd=work, log=work / "iverilog-orig.log", timeout_s=600,
    )  # fmt: skip
    new = _errors(work / "iverilog.log")
    return vl == 0, False, bool(new) and new <= _errors(work / "iverilog-orig.log")


