def W(name):  # the X__base declaration, with its Verilator BLKANDNBLK waiver
    return f"/* verilator lint_off BLKANDNBLK */ {name} /* verilator lint_on BLKANDNBLK */"


def _rw(fname):
    return rewrite(analyze(FIX / fname, ALL[fname], GLBL))


