def _random_tb(model, inputs, outputs):
    """A testbench toggling ``inputs`` (C: a clock) from an LFSR, printing ``outputs``
    between changes (the reviewer's VZCE harness, generalised)."""
    others = [i for i in inputs if i != "C"]
    decl = "".join(f"  reg {i} = 0;\n" for i in inputs)
    decl += "".join(f"  wire [{w - 1}:0] {o};\n" for o, w in outputs.items())
    conns = ", ".join(f".{p}({p})" for p in [*outputs, *inputs])
    fmt = " ".join(f"{p}=%h" for p in [*outputs, *inputs])
    args = ", ".join([*outputs, *inputs])
    drive = " ".join(
        f"if (lfsr[{k + 1}] ^ lfsr[{k + 8}]) {i} = lfsr[{k + 11}];" for k, i in enumerate(others)
    )
    return f"""`timescale 1ps/1ps
module tb;
{decl}  reg [31:0] lfsr = 32'hACE1_1234;
  integer i;
  {model} dut ({conns});
  task step; lfsr = {{lfsr[30:0], lfsr[31]^lfsr[21]^lfsr[1]^lfsr[0]}}; endtask
  initial begin
    for (i = 0; i < 3000; i = i + 1) begin
      step; C = ~C; if (lfsr[3] & lfsr[5]) begin {drive} end
      #2 $display("OUT %0t {fmt}", $time, {args});
      #1 step; if (lfsr[4] & lfsr[9]) begin {drive} end
      #2 $display("OUT %0t {fmt}", $time, {args});
      #5;
    end
    $finish;
  end
endmodule
"""


@pytest.mark.container
@pytest.mark.skipif(_no_image, reason="xut-sim image not built")
@pytest.mark.parametrize(
    "fname,inputs,outputs",
    [
        ("vz_trig.v", ["C", "D", "CLR", "PRE"], {"Q": 1}),
        ("vz_ifelse.v", ["C", "D", "C2", "E"], {"Q": 1}),
        ("vz_select.v", ["C", "D", "R"], {"Q": 3}),
    ],
)
def test_accepted_fixture_matches_original_on_icarus_and_verilator(fname, inputs, outputs):
    """Original on Icarus == transformed on Icarus == transformed on Verilator, under random
    stimulus that includes releases coincident with clock edges (ruling S28)."""
    model = ALL[fname]
    work = repo_root() / "build" / "vz-lint" / f"{model}-random"
    shutil.rmtree(work, ignore_errors=True)
    tb = _random_tb(model, inputs, outputs)
    runs = {
        "orig": (lambda d: shutil.copy(FIX / fname, d / "m.v"), "iverilog"),
        "vz": (lambda d: write_text(d / "m.v", _rw(fname)), "iverilog"),
        "vzv": (lambda d: write_text(d / "m.v", _rw(fname)), "verilator"),
    }
    ex = DockerExecutor()
    out = {}
    for name, (put, sim) in runs.items():
        d = work / name
        d.mkdir(parents=True)
        put(d)
        (d / "tb.v").write_text(tb)
        shutil.copy(GLBL, d / "glbl.v")
        cmd = (
            "iverilog -g2012 -o sim.vvp -s tb -s glbl tb.v m.v glbl.v && vvp -n sim.vvp"
            if sim == "iverilog"
            else "verilator --binary --timing -Wno-fatal -Wno-lint -Wno-style -Wno-MULTITOP "
            "tb.v m.v glbl.v -o vtb && ./obj_dir/vtb"
        )
        log = d / "run.log"
        assert ex.run(["bash", "-c", cmd], cwd=d, log=log, timeout_s=600) == 0, log.read_text()
        out[name] = [ln for ln in log.read_text().splitlines() if ln.startswith("OUT ")]
    assert len(out["orig"]) == 6000
    assert out["vz"] == out["orig"]
    assert out["vzv"] == out["orig"]
