def _write_result(root: Path, ms: str, rows: list[Row], glob: str | None = None) -> None:
    doc = {
        "model_source": ms, **_meta(), "models_glob": glob, "models": len(rows),
        "configurations": 2 * len(rows), "rows": [dataclasses.asdict(r) for r in rows],
    }  # fmt: skip
    d = root / "build" / "portability" / ("partial" if glob else "")
    d.mkdir(parents=True, exist_ok=True)
    (d / f"{ms}.json").write_text(json.dumps(doc))


def test_load_results_reads_full_runs_only(tmp_path):
    _write_result(tmp_path, "unisim-2025.2", ROWS)
    _write_result(tmp_path, "unisim-gh-2020.1", ROWS[:1], glob="FD*")  # partial/: ignored
    rows, meta = portability.load_results(tmp_path)
    assert list(rows) == ["unisim-2025.2"] and rows["unisim-2025.2"] == ROWS
    assert meta["head"] == "abc1234" and meta["sources"]["unisim-2025.2"]["configurations"] == 8


def test_status_generate_also_writes_portability_when_results_exist(tmp_path, monkeypatch):
    (tmp_path / "status" / "7series").mkdir(parents=True)
    (tmp_path / "log").mkdir()
    monkeypatch.setattr("xut.paths.repo_root", lambda start=None: tmp_path)
    monkeypatch.setattr("xut.status.current_branch", lambda: "main")
    monkeypatch.setattr("xut.workunits.load_units", lambda root: {})
    monkeypatch.setattr("xut.workunits.load_family", lambda root: "7series")
    r = CliRunner().invoke(main, ["status", "generate"])
    assert r.exit_code == 0, r.output
    assert not (tmp_path / "status" / "PORTABILITY.md").exists()
    _write_result(tmp_path, "unisim-2025.2", ROWS)
    r = CliRunner().invoke(main, ["status", "generate"])
    assert r.exit_code == 0 and "PORTABILITY.md" in r.output, r.output
    got = parse((tmp_path / "status" / "PORTABILITY.md").read_text())
    assert got == {"unisim-2025.2": {r.model: r for r in ROWS}}


