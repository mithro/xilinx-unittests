TOY = HdlModule(
    "TOY",
    Path("TOY.v"),
    ports=[
        HdlPort("D", "input", 4),
        HdlPort("C", "input", 1),
        HdlPort("Q", "output", 1),
        HdlPort("IO", "inout", 2),
    ],
    params=[HdlParam("INIT", "bits", 1, "1'b0")],
)


def test_smoke_top_ties_inputs_low_and_leaves_outputs_and_inouts_as_wires():
    text = smoke_top(TOY)
    assert text.startswith(
        "// SPDX-License-Identifier: Apache-2.0\n// GENERATED by xut portability"
    )
    assert "`timescale 1ps / 1ps\nmodule xut_smoke;\n" in text
    assert "  reg  [3:0] i_D = 0;\n  reg  [0:0] i_C = 0;\n" in text
    assert "  wire [0:0] o_Q;\n  wire [1:0] io_IO;\n" in text
    assert "  TOY dut (.D(i_D), .C(i_C), .Q(o_Q), .IO(io_IO));\n" in text
    assert '  initial begin #200000; $display("XUT_SMOKE_OK"); $finish; end\nendmodule\n' in text


def test_smoke_top_passes_overrides_as_parameters():
    text = smoke_top(TOY, {"INIT": "1'b1", "A_STR": '"X"'})
    assert '  TOY #(.A_STR("X"), .INIT(1\'b1)) dut (' in text


