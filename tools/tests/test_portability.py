def test_configurations_add_generate_configs_and_each_inversion(tmp_path):
    f = tmp_path / "INV.v"
    f.write_text(
        "// SPDX-License-Identifier: Apache-2.0\n"
        "module INV #(parameter [0:0] IS_C_INVERTED = 1'b0, parameter [0:0] IS_D_INVERTED "
        '= 1\'b0, parameter MODE = "A") (output Q, input C, input D);\n'
        '  generate if (MODE == "B") begin : g assign Q = D; end else begin : h assign Q = C;'
        " end endgenerate\nendmodule\n"
    )
    from xut.catalog.unisim import parse_module

    cfgs, notes = configurations(f, parse_module(f, "INV"))
    assert cfgs == [{}, {"MODE": '"B"'}, {"IS_C_INVERTED": "1'b1"}, {"IS_D_INVERTED": "1'b1"}]
    assert notes == []


