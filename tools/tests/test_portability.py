def test_classify_ignores_warnings_and_non_error_lines():
    log = "%Warning-REALCVT: /m/X.v:1: real converted\nINFO: using a real clock\n%Error: boom"
    assert classify(log) == "other"
    assert failure(log, 1) == "other: %Error: boom"


def test_failure_without_an_error_line_names_the_exit():
    assert failure("xut-smoke: build exit 0\nxut-smoke: run exit 0\n", 0) == (
        "other: exit 0, no XUT_SMOKE_OK"
    )
    assert failure("", None) == "other: the script did not finish"


