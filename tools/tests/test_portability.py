@pytest.mark.container
def test_run_smoke_on_the_fixture_model_source(tmp_path, fixture_source):
    root = tmp_path / "root"
    root.mkdir()
    lines: list[str] = []
    rows = portability.run_smoke(fixture_source, jobs=8, root=root, progress=lines.append)
    got = {r.model: r for r in rows}
    assert sorted(got) == sorted(p.stem for p in fixture_source.unisims.glob("*.v"))
    assert (got["VZTRIG"].iverilog, got["VZTRIG"].verilator) == ("yes", "yes")
    assert (got["VZTRIG"].verilatorize, got["VZTRIG"].equiv) == ("transformed", "pass")
    assert got["VZTRIG"].triggers == ["CLR", "PRE", "glbl.GSR"]
    assert got["PLAIN"] == Row("PLAIN", "yes", "yes", "unchanged", "—")
    assert got["VZPARENT"].verilatorize == "unchanged (gated: VZCHILD)"
    assert (got["VZPARENT"].equiv, got["VZPARENT"].verilator) == ("pass", "yes")
    assert got["VZBADSEL"].verilator.startswith("no: verilatorize: ")
    # a procedural assign to a bit select: pyslang cannot read its ports, so no smoke top
    assert got["VZBADSEL"].iverilog == "no"
    assert got["VZBADSEL"].reason.startswith("iverilog: other: smoke: cannot read its ports: 1 ")
    assert got["BLOCKED"].verilator == "no: blocked by refused dependency VZBADSEL"
    sip = got["SIPUSER"]
    assert (sip.iverilog, sip.verilator) == ("no", "no")
    assert "iverilog: secureip: " in sip.reason and "verilator: secureip: " in sip.reason
    stop = got["STOPPER"]
    assert (stop.iverilog, stop.verilator) == ("no", "no"), stop
    assert "iverilog: other: Error: [Unisim STOPPER-1]" in stop.reason
    assert stop.reason.split("; ")[0].endswith("[IS_C_INVERTED=1'b1]"), stop.reason
    # the result file and the progress lines
    doc = json.loads((root / "build/portability/test-src.json").read_text())
    assert [r["model"] for r in doc["rows"]] == sorted(got)
    assert doc["configurations"] == 8  # STOPPER has 2 (IS_C_INVERTED flipped), VZBADSEL 0
    smoke = [ln for ln in lines if ln.startswith("progress: done=")]
    total = int(smoke[0].split("total=")[1].split()[0])
    assert smoke[-1].startswith(f"progress: done={total} total={total} ")
    assert not any(ln.startswith("progress: done=") for ln in lines[: lines.index(smoke[0])])
    work = root / "build/portability/test-src"
    assert (work / "VZTRIG/default/smoke.v").is_file()
    assert (work / "VZTRIG/default/verilator.rc").read_text().strip() == "0"
    assert not (work / "VZTRIG/default/obj").exists()  # removed after the run
    assert not (work / "VZBADSEL/default/verilator.sh").exists()  # refused: never built
    assert parse(render({"test-src": rows}, _meta()))["test-src"] == got
